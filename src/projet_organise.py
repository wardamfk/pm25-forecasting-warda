    Q3 = data.quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    iqr_outliers = (
        (data < lower_bound) |
        (data > upper_bound)
    ).sum()

    # Méthode Z-score
    z_scores = np.abs(zscore(data))
    z_outliers = (z_scores > 3).sum()

    # Méthode Isolation Forest
    iso = IsolationForest(
        contamination="auto",
        random_state=42
    )

    predictions = iso.fit_predict(data.to_frame())
    if_outliers = (predictions == -1).sum()

    results.append({
        "Variable": col,
        "IQR_Outliers": int(iqr_outliers),
        "IQR_Percentage": round(iqr_outliers / len(data) * 100, 2),
        "Zscore_Outliers": int(z_outliers),
        "Zscore_Percentage": round(z_outliers / len(data) * 100, 2),
        "IsolationForest_Outliers": int(if_outliers),
        "IF_Percentage": round(if_outliers / len(data) * 100, 2)
    })

